-- Maven ↔ OnTarget v2 reconciliation foundation.
-- This migration is deliberately provider-neutral: no Maven endpoint is
-- inferred here. The reconcile worker must use the existing, documented
-- client once its endpoint contract is available.

ALTER TABLE public.maven_transactions
  ADD COLUMN IF NOT EXISTS created_at_utc timestamptz,
  ADD COLUMN IF NOT EXISTS modified_at_utc timestamptz,
  ADD COLUMN IF NOT EXISTS paid_source text,
  ADD COLUMN IF NOT EXISTS provider_commission numeric,
  ADD COLUMN IF NOT EXISTS needs_review boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS reconciled_from_provider boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS row_hash text;

DO $$ BEGIN
  ALTER TABLE public.maven_transactions
    ADD CONSTRAINT maven_transactions_paid_source_ck
    CHECK (paid_source IS NULL OR paid_source IN ('provider_auto','operator','manual_edit','reconciliation'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE OR REPLACE FUNCTION public.parse_maven_utc(p_value text)
RETURNS timestamptz
LANGUAGE plpgsql IMMUTABLE SET search_path TO public AS $$
DECLARE v text := nullif(trim(p_value), '');
BEGIN
  IF v IS NULL THEN RETURN NULL; END IF;
  -- Maven exports both ISO values (with Z/offset) and naive UTC text.
  IF v ~* '(z|[+-][0-9]{2}:[0-9]{2})$' THEN
    RETURN v::timestamptz;
  END IF;
  RETURN replace(v, 'T', ' ')::timestamp AT TIME ZONE 'UTC';
EXCEPTION WHEN others THEN
  RETURN NULL;
END $$;

CREATE OR REPLACE FUNCTION public.trg_maven_timestamp_columns()
RETURNS trigger LANGUAGE plpgsql SET search_path TO public AS $$
BEGIN
  NEW.created_at_utc := public.parse_maven_utc(NEW.created_utc);
  NEW.modified_at_utc := public.parse_maven_utc(NEW.modified_utc);
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_maven_timestamp_columns ON public.maven_transactions;
CREATE TRIGGER trg_maven_timestamp_columns
BEFORE INSERT OR UPDATE OF created_utc, modified_utc ON public.maven_transactions
FOR EACH ROW EXECUTE FUNCTION public.trg_maven_timestamp_columns();

UPDATE public.maven_transactions
SET created_at_utc = public.parse_maven_utc(created_utc),
    modified_at_utc = public.parse_maven_utc(modified_utc)
WHERE created_at_utc IS DISTINCT FROM public.parse_maven_utc(created_utc)
   OR modified_at_utc IS DISTINCT FROM public.parse_maven_utc(modified_utc);

