CREATE OR REPLACE VIEW public.v_provider_vs_local_mismatch AS
SELECT * FROM public.maven_transactions WHERE needs_review
UNION ALL
SELECT mt.* FROM public.maven_transactions mt
WHERE mt.last_status_change >= now() - interval '7 days' AND mt.reconciled_from_provider = true;
