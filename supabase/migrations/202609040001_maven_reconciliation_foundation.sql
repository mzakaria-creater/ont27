-- Fee booking is intentionally explicit and does not change the configured
-- 3%/4% rates. payin_commission_pct is stored as a percentage (3 => 3%).
CREATE OR REPLACE FUNCTION public.book_deposit_fees(p_tx_id bigint)
RETURNS jsonb LANGUAGE plpgsql SET search_path TO public AS $$
DECLARE t public.maven_transactions; h record; provider numeric; fee numeric; comm numeric;
BEGIN
  SELECT * INTO t FROM public.maven_transactions WHERE tx_id = p_tx_id FOR UPDATE;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok',false,'error','not_found'); END IF;
  SELECT mh.commission_rate, mh.payin_commission_pct INTO h
  FROM public.merchants_hierarchy mh
  WHERE mh.name = t.sub_merchant OR mh.name = t.merchant
  ORDER BY (mh.name = t.sub_merchant) DESC, mh.active DESC, mh.id DESC LIMIT 1;
  fee := COALESCE(t.amount,0) * COALESCE(h.commission_rate,0);
  comm := COALESCE(t.amount,0) * COALESCE(h.payin_commission_pct,0) / 100;
  provider := CASE
    WHEN COALESCE(t.raw, '{}'::jsonb)->>'Commision' ~ '^[-+]?[0-9]+(\\.[0-9]+)?$' THEN (t.raw->>'Commision')::numeric
    WHEN COALESCE(t.raw, '{}'::jsonb)->>'Commission' ~ '^[-+]?[0-9]+(\\.[0-9]+)?$' THEN (t.raw->>'Commission')::numeric
    WHEN COALESCE(t.maven_raw_row, '{}'::jsonb)->>'Commision' ~ '^[-+]?[0-9]+(\\.[0-9]+)?$' THEN (t.maven_raw_row->>'Commision')::numeric
    ELSE NULL END;
  UPDATE public.maven_transactions SET fees = fee, commission = comm, provider_commission = provider WHERE tx_id = p_tx_id;
  RETURN jsonb_build_object('ok',true,'fees',fee,'commission',comm,'provider_commission',provider);
END $$;

CREATE OR REPLACE VIEW public.v_merchant_daily_utc AS
SELECT merchant, (created_at_utc AT TIME ZONE 'UTC')::date AS day_utc,
  count(*) FILTER (WHERE upper(status)='PAID') AS paid_n,
  COALESCE(sum(amount) FILTER (WHERE upper(status)='PAID'),0) AS paid_amt,
  count(*) FILTER (WHERE upper(status)='DECLINED') AS declined_n,
  COALESCE(sum(amount) FILTER (WHERE upper(status)='DECLINED'),0) AS declined_amt,
  count(*) FILTER (WHERE upper(status) NOT IN ('PAID','DECLINED')) AS other_n,
  COALESCE(sum(amount) FILTER (WHERE upper(status) NOT IN ('PAID','DECLINED')),0) AS other_amt,
  COALESCE(sum(fees) FILTER (WHERE upper(status)='PAID'),0) AS fees,
  COALESCE(sum(commission) FILTER (WHERE upper(status)='PAID'),0) AS commission,
  COALESCE(sum(provider_commission) FILTER (WHERE upper(status)='PAID'),0) AS provider_commission
FROM public.maven_transactions GROUP BY merchant, (created_at_utc AT TIME ZONE 'UTC')::date;

