create table if not exists public.device_prefix_map (
  id bigint generated by default as identity primary key,
  prefix text not null check (prefix ~ '^ont(?:10|[1-9])$'),
  employee text not null check (length(btrim(employee)) > 0),
  wallet_number text not null check (wallet_number ~ '^01[0-9]{9}$'),
  sim_slot smallint not null check (sim_slot in (1, 2)),
  active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.device_prefix_map enable row level security;
revoke all on table public.device_prefix_map from anon, authenticated;

drop policy if exists device_prefix_map_service_role on public.device_prefix_map;
create policy device_prefix_map_service_role
on public.device_prefix_map
for all
to service_role
using (true)
with check (true);

create unique index if not exists device_prefix_map_prefix_wallet_idx
  on public.device_prefix_map (prefix, wallet_number);

create unique index if not exists device_prefix_map_active_slot_idx
  on public.device_prefix_map (prefix, sim_slot)
  where active;

create index if not exists device_prefix_map_wallet_idx
  on public.device_prefix_map (wallet_number)
  where active;

alter table public.inbound_sms
  add column if not exists device_prefix text,
  add column if not exists resolved_employee text,
  add column if not exists wallet_resolution_source text;

create index if not exists inbound_sms_device_prefix_received_idx
  on public.inbound_sms (device_prefix, received_at desc);

create or replace function public.touch_device_prefix_map_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

revoke execute on function public.touch_device_prefix_map_updated_at() from public, anon, authenticated;

drop trigger if exists trg_device_prefix_map_updated_at on public.device_prefix_map;
create trigger trg_device_prefix_map_updated_at
before update on public.device_prefix_map
for each row
execute function public.touch_device_prefix_map_updated_at();
